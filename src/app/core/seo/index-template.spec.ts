import { readFileSync } from 'node:fs';
import { defaultLocale } from 'intlayer';
import { ORGANIZATION } from './organization';

/**
 * `src/index.html` hard-codes a title, a description, Open Graph tags and `lang="en"`.
 *
 * Every one of the 87 routes is prerendered with its own locale and its own metadata, and
 * `DocumentMeta` replaces all of this on navigation, so these values are only ever seen before
 * hydration or by something served unprerendered. That makes them easy to forget: they are a
 * second copy of copy that actually lives in `document-meta.content.ts` and `organization.ts`,
 * and nothing noticed when the two disagreed.
 *
 * So they are pinned here. The template is allowed to carry default-locale metadata - that is
 * the sensible fallback - but it is not allowed to carry metadata that has quietly drifted away
 * from the source the rest of the site renders from.
 */
const template = readFileSync('src/index.html', 'utf8');

/**
 * The resolved dictionary, which is what the application actually renders. Generated by
 * `intlayer build`, which every `npm test` run does first.
 */
const homeMeta = (() => {
  const path = '.intlayer/dictionary/document-meta.json';
  let raw: string;
  try {
    raw = readFileSync(path, 'utf8');
  } catch {
    throw new Error(`${path} is missing - run \`npm run pretypecheck\` to generate it`);
  }
  const home = JSON.parse(raw).content?.translation?.[defaultLocale]?.pages?.home;
  if (typeof home?.title !== 'string' || typeof home?.description !== 'string') {
    throw new Error(`${path} has no ${defaultLocale} home title/description`);
  }
  return { title: home.title as string, description: home.description as string };
})();

/**
 * Every `<meta>` tag's attribute text. Prettier wraps the long ones across several lines, so
 * the tags are collected whole first and read attribute by attribute, rather than matched by
 * one expression that would have to anticipate the formatting.
 */
const metaTags = [...template.matchAll(/<meta\b([^>]*)>/gs)].map((match) => match[1]);

const attribute = (tag: string, name: string): string | undefined =>
  new RegExp(`\\b${name}="([^"]*)"`, 's').exec(tag)?.[1];

/** The content of the `<meta>` tag carrying the given `name=` or `property=`. */
const metaContent = (kind: 'name' | 'property', value: string): string | undefined => {
  const tag = metaTags.find((candidate) => attribute(candidate, kind) === value);
  return tag === undefined ? undefined : attribute(tag, 'content');
};

describe('src/index.html', () => {
  it('declares the default locale, which the app then replaces per route', () => {
    // `app.ts` assigns `documentElement.lang` from the active locale, and the prerendered
    // documents carry hy/ru correctly; this pins the pre-hydration default to the same default.
    expect(/<html\s+lang="([^"]+)"/.exec(template)?.[1]).toBe(defaultLocale);
  });

  it('carries the same title the default locale renders', () => {
    expect(/<title>([^<]*)<\/title>/.exec(template)?.[1]).toBe(homeMeta.title);
  });

  it('carries the same description the default locale renders', () => {
    expect(metaContent('name', 'description')).toBe(homeMeta.description);
  });

  it('keeps its Open Graph title and description in step with that same source', () => {
    expect(metaContent('property', 'og:title')).toBe(homeMeta.title);
    expect(metaContent('property', 'og:description')).toBe(homeMeta.description);
  });

  it('names the organization from the one place that defines it', () => {
    expect(metaContent('property', 'og:site_name')).toBe(ORGANIZATION.name);
  });

  it('declares an og:locale matching the default locale', () => {
    // `OG_LOCALES` in document-meta.ts is module-private, so the mapping is restated here;
    // the point is that the template cannot claim a locale other than the default one.
    const expected: Record<string, string> = { en: 'en_US', hy: 'hy_AM', ru: 'ru_RU' };
    expect(metaContent('property', 'og:locale')).toBe(expected[defaultLocale]);
  });
});
